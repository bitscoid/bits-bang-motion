/* =========================================================
   audio/words.json  ->  audio/cues.js

   Kenapa JS, bukan JSON: skill ini menjanjikan index.html yang bisa
   diklik dua kali. fetch('words.json') diblokir CORS di file://, tapi
   <script src="audio/cues.js"> biasa tidak. Jadi timing ikut sebagai
   script, bukan sebagai data yang di-fetch.

   Hasilnya ditulis sekali, jangan diedit tangan — regenerate dari
   words.json setiap kali audio berubah.

   Pakai:
     node scripts/make-cues.mjs
     node scripts/make-cues.mjs --words audio/words.json --out audio/cues.js
   ========================================================= */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { mkdir } from 'node:fs/promises';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};

const WORDS = arg('words', 'audio/words.json');
const OUT   = arg('out', 'audio/cues.js');
const TAIL  = Number(arg('tail', 0.6));   // ruang setelah kata terakhir
const DELAY = process.argv.includes('--no-delay') ? 0 : null;

const data = JSON.parse(await readFile(WORDS, 'utf8'));

if (!Array.isArray(data.segments) || !data.segments.length) {
  console.error(`${WORDS} has no segments — run scripts/asr-words.py first.`);
  process.exit(1);
}

const off = DELAY ?? Number(data.vo_delay ?? 1.0);
const shift = t => Math.round((Number(t) + off) * 1000) / 1000;

const segments = data.segments.map(s => ({
  start: shift(s.start),
  end: shift(s.end),
  text: s.text_display || s.text || '',
  words: (s.words || [])
    .filter(w => w.word && String(w.word).trim())
    .map(w => ({
      w: String(w.word).trim(),
      t: shift(w.start),
      e: shift(w.end),
    })),
}));

const last = segments[segments.length - 1];
const dur = Math.round((last.end + TAIL) * 1000) / 1000;

const body = `/* generated by scripts/make-cues.mjs from ${WORDS} — do not edit */
window.CUES = {
  voDelay: ${off},
  dur: ${dur},
  segments: ${JSON.stringify(segments, null, 1)}
};
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body, 'utf8');

const words = segments.reduce((n, s) => n + s.words.length, 0);
console.log(`wrote ${OUT}`);
console.log(`  ${segments.length} segments · ${words} words · dur ${dur}s (voDelay ${off})`);

const empty = segments.filter(s => !s.words.length).length;
if (empty) console.warn(`  WARNING: ${empty} segment(s) have no words — saySync will skip them`);
if (off !== (data.vo_delay ?? 1.0)) console.warn(`  NOTE: vo_delay overridden to ${off}`);